// Возвращает индекс в таблице или -1
static int char_index(char c) {
    if (c >= 'a' && c <= 'z') c -= 32;   // в верхний регистр
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= '0' && c <= '9') return 26 + (c - '0');
    return -1;
}

void cmd_banner(const char* text) {
    if (!text || !*text) { println("Usage: banner <text>"); return; }

    int len = strlen(text);
    if (len > 12) len = 12;   // ограничение 80 колонок: 12 * (5+1) = 72

    // 7 строк шрифта
    for (int row = 0; row < 7; row++) {
        for (int ci = 0; ci < len; ci++) {
            int idx = char_index(text[ci]);
            if (idx < 0) {
                // пробел
                print("      ");
                continue;
            }
            uint8_t bits = font5x7[idx][row];
            for (int b = 4; b >= 0; b--)
                print_char((bits >> b) & 1 ? '#' : ' ');
            print_char(' ');  // межсимвольный пробел
        }
        print_char('\n');
    }
}