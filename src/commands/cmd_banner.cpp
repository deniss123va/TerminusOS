// ─── Индекс символа в таблице, -1 = пробел/неизвестный ───────────────────────
static int char_index(char c) {
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= '0' && c <= '9') return 26 + (c - '0');
    if (c == '!') return 36;
    if (c == '?') return 37;
    if (c == '.') return 38;
    if (c == '-') return 39;
    return -1;  // пробел и всё остальное
}

// ─── Команда ─────────────────────────────────────────────────────────────────
void cmd_banner(const char* text) {
    if (!text || !*text) { println("Usage: banner <text>"); return; }

    // 12 символов × (5 px + 1 gap) = 72 — помещается в 80 колонок
    int len = strlen(text);
    if (len > 12) len = 12;

    // Цвет: берём foreground из текущей темы
    uint8_t color = (theme_bg << 4) | (theme_fg & 0x0F);

    for (int row = 0; row < 7; row++) {
        for (int ci = 0; ci < len; ci++) {
            int idx = char_index(text[ci]);
            if (idx < 0) {
                // пробел: 6 пустых колонок
                for (int k = 0; k < 6; k++) print_char(' ');
                continue;
            }
            uint8_t bits = font5x7[idx][row];
            for (int b = 4; b >= 0; b--)
                print_char_colored((bits >> b) & 1 ? '#' : ' ', color);
            print_char(' ');  // межсимвольный пробел
        }
        print_char('\n');
    }
}